export function getCategoryById(id: number): Category {
  const match = events.find((item) => item.id === id);
  if (match) return match;

  const first = events[0];
  if (!first) {
    throw new Error('Список категорий пуст');
  }
  return first;
}

export function getCategoryIndex(id: number): number {
  const index = events.findIndex((item) => item.id === id);
  return index === -1 ? 0 : index;
}

export function getNeighborCategory(id: number, direction: 1 | -1): Category {
  const index = getCategoryIndex(id);
  const nextIndex = (index + direction + events.length) % events.length;
  return events[nextIndex] ?? getCategoryById(id);
}

export function getEventAt(category: Category, index: number): EventItem {
  const match = category.events[index] ?? category.events[0];
  if (!match) {
    throw new Error(`В категории «${category.title}» нет фактов`);
  }
  return match;
}
